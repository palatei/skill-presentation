import type { GenerateRequestBody } from "./types";

const TONE_LABELS: Record<GenerateRequestBody["tone"], string> = {
  business: "деловой, уверенный, без лишней воды",
  friendly: "дружелюбный, тёплый, но профессиональный",
  bold: "смелый, запоминающийся, с характером",
};

export function buildPresentationPrompt(input: GenerateRequestBody): string {
  const audienceBlock = input.audience
    ? `\n- Целевая аудитория: ${input.audience}`
    : "";
  const uniquenessBlock = input.uniqueness
    ? `\n- Уникальность / отличие: ${input.uniqueness}`
    : "";

  return `Ты — опытный копирайтер и карьерный стратег. Напиши на русском языке продающую текстовую презентацию человека (go-to-market pitch о себе как о продукте/эксперте).

Требования к стилю:
- Тон: ${TONE_LABELS[input.tone]}
- Язык: только русский
- Без выдуманных фактов — опирайся только на данные ниже
- Живой текст, без канцелярита и шаблонных клише
- Используй Markdown: заголовки ##, списки, выделение ** где уместно

Структура (обязательные разделы с этими заголовками):
## Заголовок
Короткий цепляющий заголовок (1 строка)

## Кто я
2–4 предложения: представление, ниша, позиционирование

## Ценность
Что получает клиент/работодатель/партнёр, конкретная польза

## Навыки
Структурированный список ключевых навыков на основе вводных

## Для кого
Кому подходит сотрудничество (если аудитория не указана — выведи логично из ниши)

## Призыв к действию
Один чёткий CTA (созвон, бриф, пилот, резюме — уместно контексту)

## Elevator pitch
Ровно 2–3 предложения, устная версия за 20–30 секунд

Данные о человеке:
- Имя / как представляться: ${input.name}
- Ниша / сфера: ${input.niche}
- Навыки и умения: ${input.skills}
- Опыт / бэкграунд: ${input.experience}${audienceBlock}${uniquenessBlock}

Верни только готовый текст презентации в Markdown, без пояснений до или после.`;
}
